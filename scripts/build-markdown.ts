import fs from 'node:fs';
import path from 'node:path';
import {
  STATIC_ROUTE_REGISTRY,
  formatPageMarkdown,
  formatLlmsTxt,
  formatLlmsFullTxt,
} from '../lib/markdown/format.ts';
import {
  REPO_ROOT,
  resolveSiteDataBundle,
  getHtmlFilePath,
} from '../lib/markdown/resolve.ts';

const MD_HEADERS_START = '# static-md-headers:start - generated by scripts/build-markdown.ts, do not edit by hand';
const MD_HEADERS_END = '# static-md-headers:end';

function buildFilesHeaderBlock(entries: Array<{ filename: string; canonicalUrl: string }>): string {
  const lines: string[] = [
    MD_HEADERS_START,
    '<IfModule mod_headers.c>',
  ];
  for (const e of entries) {
    lines.push(`    <Files "${e.filename}">`);
    lines.push(`        Header set Link '<${e.canonicalUrl}>; rel="canonical"'`);
    lines.push('    </Files>');
  }
  lines.push('</IfModule>');
  lines.push(MD_HEADERS_END);
  return lines.join('\n');
}

function updateHtmlAlternateLinks(): number {
  let updatedCount = 0;

  for (const meta of Object.values(STATIC_ROUTE_REGISTRY)) {
    const htmlPath = getHtmlFilePath(meta.canonicalPath, REPO_ROOT);
    const html = fs.readFileSync(htmlPath, 'utf8');
    const linkTag = `<link rel="alternate" type="text/markdown" href="${meta.mdUrl}">`;

    let nextHtml = html;
    if (/rel=["']alternate["'][^>]*type=["']text\/markdown["']/i.test(html)) {
      nextHtml = html.replace(
        /<link\b[^>]*rel=["']alternate["'][^>]*type=["']text\/markdown["'][^>]*>/i,
        linkTag
      );
    } else {
      // Insert immediately after <link rel="canonical" ...>
      const canonRegex = /(<link\b[^>]*rel=["']canonical["'][^>]*>)/i;
      if (canonRegex.test(html)) {
        nextHtml = html.replace(canonRegex, `$1\n  ${linkTag}`);
      }
    }

    if (nextHtml !== html) {
      fs.writeFileSync(htmlPath, nextHtml, 'utf8');
      updatedCount++;
    }
  }

  // Ensure noindex pages do NOT carry type="text/markdown" alternate links
  const noindexFiles = [
    '404.html',
    'login.html',
    'exam.html',
    'certificate.html',
    'wo.html',
    'header.html',
    'footer.html',
  ];
  for (const rel of noindexFiles) {
    const p = path.join(REPO_ROOT, rel);
    if (!fs.existsSync(p)) continue;
    const html = fs.readFileSync(p, 'utf8');
    const cleaned = html.replace(
      /\s*<link\b[^>]*rel=["']alternate["'][^>]*type=["']text\/markdown["'][^>]*>/gi,
      ''
    );
    if (cleaned !== html) {
      fs.writeFileSync(p, cleaned, 'utf8');
    }
  }

  return updatedCount;
}

function updateHtaccessFiles(): void {
  const rootEntries: Array<{ filename: string; canonicalUrl: string }> = [];
  const newsEntries: Array<{ filename: string; canonicalUrl: string }> = [];
  const courseEntries: Array<{ filename: string; canonicalUrl: string }> = [];

  for (const meta of Object.values(STATIC_ROUTE_REGISTRY)) {
    const relMd = meta.mdPath.slice(1); // strip leading /
    if (relMd.startsWith('news/')) {
      newsEntries.push({
        filename: path.basename(relMd),
        canonicalUrl: meta.canonicalUrl,
      });
    } else if (relMd.startsWith('course/')) {
      courseEntries.push({
        filename: path.basename(relMd),
        canonicalUrl: meta.canonicalUrl,
      });
    } else {
      rootEntries.push({
        filename: path.basename(relMd),
        canonicalUrl: meta.canonicalUrl,
      });
    }
  }

  // 1. Update news/.htaccess
  const newsHtaccessPath = path.join(REPO_ROOT, 'news', '.htaccess');
  const newsHtaccessContent = [
    'PassengerEnabled off',
    '',
    buildFilesHeaderBlock(newsEntries),
    '',
  ].join('\n');
  fs.writeFileSync(newsHtaccessPath, newsHtaccessContent, 'utf8');

  // 2. Update course/.htaccess
  const courseHtaccessPath = path.join(REPO_ROOT, 'course', '.htaccess');
  const courseHtaccessContent = [
    'PassengerEnabled off',
    '',
    buildFilesHeaderBlock(courseEntries),
    '',
  ].join('\n');
  fs.writeFileSync(courseHtaccessPath, courseHtaccessContent, 'utf8');

  // 3. Update root .htaccess canonical Link headers block
  const rootHtaccessPath = path.join(REPO_ROOT, '.htaccess');
  let rootHtaccess = fs.readFileSync(rootHtaccessPath, 'utf8');
  const rootBlock = buildFilesHeaderBlock(rootEntries);

  if (rootHtaccess.includes(MD_HEADERS_START) && rootHtaccess.includes(MD_HEADERS_END)) {
    const pattern = new RegExp(
      `${MD_HEADERS_START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${MD_HEADERS_END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`
    );
    rootHtaccess = rootHtaccess.replace(pattern, rootBlock);
  } else {
    rootHtaccess = rootHtaccess.trimEnd() + '\n\n' + rootBlock + '\n';
  }
  fs.writeFileSync(rootHtaccessPath, rootHtaccess, 'utf8');
}

export function buildAllMarkdown(): {
  mdFileCount: number;
  htmlUpdatedCount: number;
} {
  const bundle = resolveSiteDataBundle(REPO_ROOT);

  // 1. Write all 75 .md files
  let mdFileCount = 0;
  for (const page of bundle.pages) {
    const outPath = path.join(REPO_ROOT, page.mdPath.slice(1));
    fs.mkdirSync(path.dirname(outPath), { recursive: true });
    const mdContent = formatPageMarkdown(page);
    fs.writeFileSync(outPath, mdContent, 'utf8');
    mdFileCount++;
  }

  // 2. Write /llms.txt and /llms-full.txt
  const llmsTxt = formatLlmsTxt(bundle);
  const llmsFullTxt = formatLlmsFullTxt(bundle);
  fs.writeFileSync(path.join(REPO_ROOT, 'llms.txt'), llmsTxt, 'utf8');
  fs.writeFileSync(path.join(REPO_ROOT, 'llms-full.txt'), llmsFullTxt, 'utf8');

  // 3. Inject <link rel="alternate" type="text/markdown" ...> into public HTML pages
  const htmlUpdatedCount = updateHtmlAlternateLinks();

  // 4. Update .htaccess files with canonical Link headers
  updateHtaccessFiles();

  return { mdFileCount, htmlUpdatedCount };
}

const isMain =
  process.argv[1] &&
  path.resolve(process.argv[1]).toLowerCase() ===
    path.resolve(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')).toLowerCase();

if (isMain) {
  const { mdFileCount, htmlUpdatedCount } = buildAllMarkdown();
  console.log(
    `Built ${mdFileCount} Markdown files, updated llms.txt & llms-full.txt, updated ${htmlUpdatedCount} HTML files, and synced .htaccess Link headers.`
  );
}
